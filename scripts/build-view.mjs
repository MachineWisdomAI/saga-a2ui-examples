import fs from 'node:fs';
import path from 'node:path';
import { build } from 'vite';
import { viteSingleFile } from 'vite-plugin-singlefile';
import { root } from './sdk-archive.mjs';

// Builds the board view into one self-contained HTML document (an MCP host mounts the exact bytes
// the server serves), then writes it as a TypeScript string constant the Worker bundles. Run after
// `npm run stage`; both outputs are ignored by Git.
//
// The page is this application's shell, apps/tic-tac-toe/view/index.html: the SAGA dragon, then
// the staged game's canonical `startView` (.stage/game/src/view.tsx), started from main.ts with a
// host-context callback for the dragon. The rules, the board and the shared "Built with saga a2ui"
// credit all come from the pinned SDK source.

const shell = path.join(root, 'apps', 'tic-tac-toe', 'view');
const out = path.join(root, '.stage', 'view');

await build({
  root: shell,
  base: './',
  configFile: false,
  logLevel: 'warn',
  plugins: [viteSingleFile()],
  build: { outDir: out, emptyOutDir: true, target: 'es2022' },
});

const html = fs.readFileSync(path.join(out, 'index.html'), 'utf8');
const generated = path.join(root, 'apps', 'tic-tac-toe', 'generated');
fs.mkdirSync(generated, { recursive: true });
fs.writeFileSync(
  path.join(generated, 'view-html.ts'),
  `// Generated by scripts/build-view.mjs from the pinned SDK source. Do not edit.\nexport const VIEW_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`Built the board view (${html.length} bytes).`);
